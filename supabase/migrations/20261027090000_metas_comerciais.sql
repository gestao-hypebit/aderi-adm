-- ── 4. Metas e realizado de anos anteriores ────────────────
CREATE TABLE public.metas (
  id             uuid          NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  ano            smallint      NOT NULL CHECK (ano BETWEEN 2000 AND 2100),
  unidade_id     smallint      NOT NULL REFERENCES public.unidades_negocio(id),
  grupo_id       smallint      NOT NULL REFERENCES public.grupos_produto(id),
  mes            smallint      NOT NULL CHECK (mes BETWEEN 1 AND 12),
  valor          numeric(14,2) NOT NULL DEFAULT 0 CHECK (valor >= 0),
  atualizado_por uuid          DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE SET NULL,
  updated_at     timestamptz   DEFAULT now(),
  UNIQUE (ano, unidade_id, grupo_id, mes)
);

CREATE TABLE public.realizado_historico (
  id         uuid          NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  ano        smallint      NOT NULL CHECK (ano BETWEEN 2000 AND 2100),
  unidade_id smallint      NOT NULL REFERENCES public.unidades_negocio(id),
  grupo_id   smallint      NOT NULL REFERENCES public.grupos_produto(id),
  mes        smallint      NOT NULL CHECK (mes BETWEEN 1 AND 12),
  valor      numeric(14,2) NOT NULL DEFAULT 0,
  origem     text,         -- ex.: "Gabriel - 2026.xlsx"
  updated_at timestamptz   DEFAULT now(),
  UNIQUE (ano, unidade_id, grupo_id, mes)
);

