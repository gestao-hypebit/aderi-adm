-- ── 7. Vendas (realizado) ──────────────────────────────────
CREATE TABLE public.vendas (
  id                    uuid        NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  data                  date        NOT NULL,
  dav                   text,
  cliente               text        NOT NULL,
  cliente_id            uuid        REFERENCES public.clientes(id) ON DELETE SET NULL,
  produto               text        NOT NULL,
  produto_id            uuid        REFERENCES public.produtos(id) ON DELETE SET NULL,
  quantidade            numeric     NOT NULL,
  preco_unitario        numeric     NOT NULL,
  faturamento           numeric     GENERATED ALWAYS AS (quantidade * preco_unitario) STORED,  -- sem arredondar, como a planilha
  grupo_id              smallint    NOT NULL REFERENCES public.grupos_produto(id),
  consultor_id          uuid        NOT NULL REFERENCES public.consultores_comerciais(id),
  unidade_id            smallint    NOT NULL REFERENCES public.unidades_negocio(id),  -- do consultor na data da venda
  modalidade            text        NOT NULL CHECK (modalidade IN ('VERDE_AGRO', 'VENDA_DIRETA')),
  tipo                  text        NOT NULL CHECK (tipo IN ('DIF', 'CONV')),
  cancelada             boolean     NOT NULL DEFAULT false,
  custo_unitario        numeric,    -- nulo = custo pendente
  frete_unitario        numeric     NOT NULL DEFAULT 0,
  desconto_unitario     numeric     NOT NULL DEFAULT 0,
  data_pagamento_compra date,
  data_recebimento      date,
  toneladas             numeric,    -- fertilizantes
  -- parâmetros vigentes no lançamento (mudar a configuração não altera vendas antigas)
  taxa_juros_mensal     numeric     NOT NULL,
  aliquota_imposto      numeric     NOT NULL,
  fator_comissao        numeric     NOT NULL,
  cotacao_id            uuid        REFERENCES public.cotacoes(id) ON DELETE SET NULL,
  importacao_id         uuid        REFERENCES public.importacoes(id) ON DELETE SET NULL,
  linha_origem          int,        -- linha da planilha importada
  observacao            text,
  criado_por            uuid        DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at            timestamptz DEFAULT now(),
  updated_at            timestamptz DEFAULT now()
);
CREATE INDEX vendas_data_idx      ON public.vendas (data);
CREATE INDEX vendas_unidade_idx   ON public.vendas (unidade_id, data);
CREATE INDEX vendas_consultor_idx ON public.vendas (consultor_id, data);
CREATE INDEX vendas_cotacao_idx   ON public.vendas (cotacao_id) WHERE cotacao_id IS NOT NULL;
-- Checagem de duplicidade (DAV + produto + quantidade + valor) — só avisa, não bloqueia
CREATE INDEX vendas_duplicidade_idx ON public.vendas (dav, produto, quantidade, preco_unitario);

-- Preenche unidade (do consultor) e parâmetros (da configuração) quando não vierem
CREATE OR REPLACE FUNCTION public.vendas_preencher()
  RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  cfg public.configuracoes%ROWTYPE;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT * INTO cfg FROM public.configuracoes WHERE id = 1;
    NEW.taxa_juros_mensal := coalesce(NEW.taxa_juros_mensal, cfg.meta_juros_mes, 0.022);
    NEW.aliquota_imposto  := coalesce(NEW.aliquota_imposto, cfg.meta_aliquota_imposto, 0.30);
    NEW.fator_comissao    := coalesce(NEW.fator_comissao, cfg.meta_fator_comissao, 0.10);
  END IF;
  IF NEW.unidade_id IS NULL OR (TG_OP = 'UPDATE' AND NEW.consultor_id IS DISTINCT FROM OLD.consultor_id) THEN
    SELECT unidade_id INTO NEW.unidade_id FROM public.consultores_comerciais WHERE id = NEW.consultor_id;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER vendas_preencher BEFORE INSERT OR UPDATE ON public.vendas
  FOR EACH ROW EXECUTE FUNCTION public.vendas_preencher();

